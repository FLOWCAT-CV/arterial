@contextmanager
def quiet():
    """
    Silences the console output of a block (nnU-Net and VMTK print a lot).

    """
    import io
    from contextlib import redirect_stdout, redirect_stderr
    sink = io.StringIO()
    with redirect_stdout(sink), redirect_stderr(sink):
        yield


@contextmanager
def timed(label):
    """
    Prints how long a block took.

    """
    start = time.time()
    yield
    print(f"{label}: {time.time() - start:.1f} s")


