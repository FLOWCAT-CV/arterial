INLINE_BACKEND = "module://matplotlib_inline.backend_inline"


def _keep_inline_plots():
    """
    nnU-Net switches matplotlib to the non-interactive Agg backend the first
    time it loads a checkpoint, which silently stops figures from showing in a
    notebook. Restore the inline backend before every cell.

    """
    try:
        from IPython import get_ipython
        shell = get_ipython()
        if shell is None:
            return
        shell.events.register("pre_run_cell", lambda *args: matplotlib.use(INLINE_BACKEND, force=True))
    except Exception:
        pass


def show(fig):
    """
    Displays a figure even if a library switched the backend during the cell.

    """
    if matplotlib.get_backend() != INLINE_BACKEND:
        try:
            from IPython.display import display
            display(fig)
            plt.close(fig)
        except Exception:
            pass
    return fig


_keep_inline_plots()


